"""Monte-Carlo test bench (nmr_twin.bench): properties, not exact numbers."""
import math

import numpy as np
import pytest

from nmr_twin import bench
from nmr_twin.checker import check_packet
from nmr_twin.service import new_twin


@pytest.fixture(scope="module")
def small_run(ctx):
    return bench.run(seed=7, n=40, ctx=ctx, save=False)


def test_generator_recovers_known_amplitudes_at_high_snr():
    """Pure Lorentzian lines (8 Hz = the intrinsic width, no shim part) at very high SNR: the fit returns the truth."""
    rng = np.random.default_rng(0)
    amps = bench._amps(0.69, 0.03)
    fid, _ = bench.synth_fid(amps, bench.NU0_3T, 8.0, 3000.0, rng, shift_hz=1.2, phase=0.3)
    fit = bench.fit_spectrum(fid, bench.NU0_3T)
    p = np.array(fit["params"])
    assert np.allclose(p[:6], amps, rtol=0.01, atol=0.003)
    assert fit["ratio"] == pytest.approx(0.69, abs=0.003)
    assert fit["lw_fit"] == pytest.approx(8.0, abs=0.1)
    assert fit["fwhm"] == pytest.approx(8.0, abs=0.6)          # StarterPack-style FWHM of NAA


def test_snr_definition_matches_starterpack_convention():
    """With the noise set for SNR 31.2 at 8.7 Hz, the recomputed SNR lands near 31 (peak height / noise SD)."""
    rng = np.random.default_rng(3)
    snrs = [bench.fit_spectrum(bench.synth_fid(bench._amps(0.69, 0.03), bench.NU0_3T, 8.7, 31.2, rng)[0], bench.NU0_3T)["snr"]
            for _ in range(8)]
    assert 26 < np.median(snrs) < 37


def test_crlb_grows_with_linewidth():
    """Same acquisition noise, broader line: the Cramer-Rao bound of Cho/Cr must grow (dossier §4.6)."""
    rng = np.random.default_rng(1)
    amps = bench._amps(0.69, 0.03)
    crlb = {}
    for lw in (8.7, 12.0, 16.0):
        vals = [bench.fit_spectrum(bench.synth_fid(amps, bench.NU0_3T, lw, 30.0, rng)[0], bench.NU0_3T)["crlb"] for _ in range(6)]
        crlb[lw] = float(np.mean(vals))
    assert crlb[8.7] < crlb[12.0] < crlb[16.0]


def test_case_draw_is_reproducible_and_independent_of_n(ctx):
    assert bench.draw_case(11, 5) == bench.draw_case(11, 5)
    a = bench.run(seed=11, n=6, ctx=ctx, save=False)
    b = bench.run(seed=11, n=3, ctx=ctx, save=False)
    assert [r["y"] for r in a["cases"][:3]] == [r["y"] for r in b["cases"]]


def test_packets_are_schema_valid_and_carry_no_truth(ctx, small_run):
    for p in small_run["packets"][:10]:
        v = check_packet(p, ctx, new_twin(ctx))
        assert not any(f.check == "schema" and f.status == "FAIL" for f in v.findings), p["packet_id"]
        assert p["origin"] == "SIMULATED" and p["value_epistemic"] == "DERIVED"
        assert len(p["source_sha256"]) == 64 and p["provenance"]["parents"]
        text = str(p)
        assert "true_" not in text and "truth" not in text
    truth_ids = {pid for c in small_run["truth_file"]["cases"] for pid in c["packets"]}
    assert truth_ids == {p["packet_id"] for p in small_run["packets"]}


def test_every_case_went_through_checker_and_twin(small_run):
    s = small_run["summary"]
    assert s["n"] == 40 and sum(s["status_counts"].values()) == 40
    assert s["n_accepted"] > 20                    # most simulated follow-ups are usable
    assert small_run["setup"]["source_warn_count"] == 0   # every packet declares the hash of its generated bytes
    for r in small_run["cases"]:
        if r["event_type"] != "reject":
            assert r["post_sd"] > 0 and math.isfinite(r["z"]) and r["d2"] >= 0
            assert r["R_factor"] == (2.0 if r["status"] == "WARN" else 1.0)


def test_coverage_and_calibration_in_sensible_band(small_run):
    h = small_run["summary"]["headline"]
    # packet intervals (after the WARN factor) should hold the truth most of the time, not always and not rarely
    assert 0.75 <= h["evidence95"] <= 1.0
    # when nothing changed, the twin's 95 % interval should hold the truth
    assert h["coverage95_nochange"] is None or h["coverage95_nochange"] >= 0.8
    # the factor the data supports is a positive, finite number, and the declared policy is the twin's
    assert 0.3 < h["fitted_warn_factor"] < 10 and h["declared_warn_factor"] == 2.0
    # a CRLB-only error bar is never more honest than the budget that contains it
    crlb = small_run["summaries"]["crlb"]["headline"]["evidence95"]
    assert crlb <= h["evidence95"] + 1e-9
